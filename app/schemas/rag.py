from typing import Any, List, Optional
from pydantic import BaseModel, Field


class RAGQuestionRequest(BaseModel):
    """Request model for asking a question against an insurance document."""

    question: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="The question regarding the policy, coverage, exclusions, or terms",
    )
    top_k: Optional[int] = Field(
        None,
        ge=1,
        le=20,
        description="Optional override for the number of relevant chunks to retrieve (defaults to RAG_TOP_K config, 5)",
    )

    model_config = {
        "json_schema_extra": {
            "example": {
                "question": "Is water damage covered by this policy?",
                "top_k": 5,
            }
        }
    }


class SourceMetadata(BaseModel):
    """Attribution metadata for a source chunk used in generating the answer."""

    file_name: str = Field(..., description="Name of the source document file")
    page_number: int = Field(..., description="Page number where the cited text is located (1-indexed)")
    chunk_id: Any = Field(..., description="Unique chunk ID or chunk index")


class RAGAnswerResponse(BaseModel):
    """Response model containing grounded answer and source attributions."""

    answer: str = Field(
        ...,
        description="Grounded, professional answer generated by Amazon Nova Lite based strictly on retrieved context",
    )
    sources: List[SourceMetadata] = Field(
        default_factory=list,
        description="List of source document chunks and page numbers supporting the answer",
    )
    document_id: Optional[int] = Field(None, description="Database ID of the document queried")
    query_id: Optional[int] = Field(None, description="MySQL query audit ID where the Q&A exchange is persisted")

    model_config = {
        "json_schema_extra": {
            "example": {
                "answer": "Water damage caused by flood or surface water is strictly excluded under this policy (Page 3).",
                "sources": [
                    {
                        "file_name": "acme_property_policy.pdf",
                        "page_number": 3,
                        "chunk_id": 103,
                    }
                ],
                "document_id": 1,
                "query_id": 1,
            }
        }
    }
