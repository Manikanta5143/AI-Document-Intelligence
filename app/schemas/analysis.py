from typing import Any, List, Optional
from pydantic import BaseModel, Field


class DocumentSummaryResponse(BaseModel):
    """Response model for document summarization."""

    document_id: int = Field(..., description="Database ID of the document")
    file_name: str = Field(..., description="Original file name of the document")
    document_type: str = Field(..., description="Document classification")
    summary: str = Field(..., description="Executive narrative summary generated by Amazon Nova Lite")
    key_points: List[str] = Field(default_factory=list, description="High-level bulleted highlights")
    model_id: str = Field(..., description="Bedrock model identifier used for generation")

    model_config = {
        "json_schema_extra": {
            "example": {
                "document_id": 1,
                "file_name": "acme_property_policy.pdf",
                "document_type": "Commercial Property",
                "summary": "Commercial Property Insurance Policy providing direct physical loss coverage...",
                "key_points": [
                    "Coverage A provides $2,500,000 for Building Property with a $5,000 standard deductible.",
                    "Flood and earth movement risks are strictly excluded.",
                ],
                "model_id": "amazon.nova-lite-v1:0",
            }
        }
    }


class StructuredInsuranceExtraction(BaseModel):
    """Structured insurance fields extracted from the source document without hallucination."""

    policy_type: Optional[str] = Field(None, description="Type of insurance policy or endorsement")
    coverage: Optional[Any] = Field(None, description="Coverage categories, limits, and schedules")
    exclusions: Optional[Any] = Field(default_factory=list, description="Explicit perils, conditions, and damages excluded")
    deductible: Optional[Any] = Field(None, description="Monetary or percentage deductible terms")
    important_conditions: Optional[Any] = Field(default_factory=list, description="Policyholder obligations, notice requirements, warranties")
    risk_indicators: Optional[Any] = Field(default_factory=list, description="Underwriting risk flags, high deductibles, coverage gaps")


class DocumentExtractionResponse(BaseModel):
    """Response model containing structured insurance extraction."""

    document_id: int = Field(..., description="Database ID of the document")
    file_name: str = Field(..., description="Original file name")
    document_type: str = Field(..., description="Document type")
    model_id: str = Field(..., description="Bedrock model used for extraction")
    extraction: StructuredInsuranceExtraction = Field(..., description="Parsed structured insurance data")
    raw_response: Optional[str] = Field(None, description="Raw model completion string")

    model_config = {
        "json_schema_extra": {
            "example": {
                "document_id": 1,
                "file_name": "commercial_policy.pdf",
                "document_type": "Commercial Property",
                "model_id": "amazon.nova-lite-v1:0",
                "extraction": {
                    "policy_type": "Commercial Property Policy",
                    "coverage": {
                        "building": "$2,500,000",
                        "personal_property": "$750,000",
                    },
                    "exclusions": ["Flood", "Earthquake", "Wear and Tear"],
                    "deductible": "$5,000 per occurrence",
                    "important_conditions": ["Prompt notice within 30 days of loss"],
                    "risk_indicators": ["2% windstorm deductible applies"],
                },
            }
        }
    }
